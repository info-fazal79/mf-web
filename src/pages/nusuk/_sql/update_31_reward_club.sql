-- =====================================================================
-- Nusuk · update 31 · Ribat Reward Club (members + tickets)
-- Run once in Supabase → SQL Editor (after update 30), BEFORE pushing.
-- Safe to run again.
--
-- Visitors sign in with Google on /nusuk/club, fill a short profile
-- (name, mobile, their Nusuk code, district …) and collect tickets for the
-- Ribat prize draw:
--   join      1  · once, when the account is made
--   ref_bonus 1  · once, extra, when they joined with someone's code
--   referral  1  · to the code's owner, for every new member who joined with it
--   copy      1  · once a day, for copying a code inside the time window
-- A member's referral code IS their Nusuk code.
-- Tickets carry the Bangladesh date (day) so each day's draw can use them.
-- Settings live in nusuk_settings.content.club (Nusuk Manager → Reward Club).
-- Tables are closed to the public; everything goes through the functions below.
-- =====================================================================

create table if not exists public.nusuk_club_members (
  user_id     uuid primary key references auth.users (id) on delete cascade,
  sl          int generated by default as identity (start with 1001) unique,
  name        text not null check (char_length(name) between 2 and 60),
  phone       text not null,
  email       text,
  nusuk_code  text not null,
  district    text,
  umrah_done  text check (umrah_done in ('yes', 'no', 'planning')),
  consent     boolean not null default false,
  referred_by uuid references public.nusuk_club_members (user_id) on delete set null,
  ref_ok      boolean not null default false,
  device      text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create unique index if not exists nusuk_club_members_phone on public.nusuk_club_members (phone);
create unique index if not exists nusuk_club_members_code on public.nusuk_club_members (lower(nusuk_code));
create index if not exists nusuk_club_members_ref on public.nusuk_club_members (referred_by);
create index if not exists nusuk_club_members_device on public.nusuk_club_members (device);

create table if not exists public.nusuk_club_tickets (
  id         bigint generated always as identity primary key,
  user_id    uuid not null references public.nusuk_club_members (user_id) on delete cascade,
  kind       text not null check (kind in ('join', 'ref_bonus', 'referral', 'copy')),
  day        date not null default public.nusuk_today(),
  from_user  uuid references public.nusuk_club_members (user_id) on delete set null,
  created_at timestamptz not null default now()
);
-- one join / one ref bonus per member, one copy ticket per member per day,
-- one referral ticket per new member
create unique index if not exists nusuk_club_t_join on public.nusuk_club_tickets (user_id) where kind = 'join';
create unique index if not exists nusuk_club_t_bonus on public.nusuk_club_tickets (user_id) where kind = 'ref_bonus';
create unique index if not exists nusuk_club_t_copy on public.nusuk_club_tickets (user_id, day) where kind = 'copy';
create unique index if not exists nusuk_club_t_ref on public.nusuk_club_tickets (from_user) where kind = 'referral';
create index if not exists nusuk_club_t_user on public.nusuk_club_tickets (user_id, day);
create index if not exists nusuk_club_t_day on public.nusuk_club_tickets (day);

alter table public.nusuk_club_members enable row level security;
alter table public.nusuk_club_tickets enable row level security;
drop policy if exists "nusuk_club_members: admin all" on public.nusuk_club_members;
create policy "nusuk_club_members: admin all" on public.nusuk_club_members for all using (public.is_admin()) with check (public.is_admin());
drop policy if exists "nusuk_club_tickets: admin all" on public.nusuk_club_tickets;
create policy "nusuk_club_tickets: admin all" on public.nusuk_club_tickets for all using (public.is_admin()) with check (public.is_admin());

-- ---------- Settings (nusuk_settings.content.club) ----------
create or replace function public.nusuk_club_cfg()
returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'on', coalesce((s.content->'club'->>'on')::boolean, false),
    'copy_from', coalesce(nullif(s.content->'club'->>'copy_from', ''), '09:00'),
    'copy_to', coalesce(nullif(s.content->'club'->>'copy_to', ''), '17:00'),
    'title', coalesce(s.content->'club'->>'title', ''),
    'rules', coalesce(s.content->'club'->>'rules', ''),
    'caption', coalesce(s.content->'club'->>'caption', ''),
    'card_line', coalesce(s.content->'club'->>'card_line', '')
  )
  from public.nusuk_settings s where s.id = 1
$$;

/** Is "now" (Bangladesh time) inside the daily copy window? Handles windows that pass midnight. */
create or replace function public.nusuk_club_in_window(p_cfg jsonb)
returns boolean
language plpgsql stable as $$
declare
  t time := (now() at time zone 'Asia/Dhaka')::time;
  a time;
  b time;
begin
  begin
    a := (p_cfg->>'copy_from')::time;
    b := (p_cfg->>'copy_to')::time;
  exception when others then
    a := '09:00'; b := '17:00';
  end;
  if a <= b then return t >= a and t < b; end if;
  return t >= a or t < b;
end $$;

create or replace function public.nusuk_club_phone(p text)
returns text
language sql immutable as $$
  select case
    when d ~ '^8801[3-9][0-9]{8}$' then substr(d, 3)
    when d ~ '^01[3-9][0-9]{8}$' then d
    else null end
  from (select regexp_replace(coalesce(p, ''), '[^0-9]', '', 'g') as d) x
$$;

/** Everything the member page needs in one call. Works signed out too (member = null). */
create or replace function public.nusuk_club_me()
returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  cfg jsonb := public.nusuk_club_cfg();
  uid uuid := auth.uid();
  m public.nusuk_club_members;
  today date := public.nusuk_today();
  ref_name text;
begin
  if uid is null then
    return jsonb_build_object('cfg', cfg, 'signed_in', false, 'member', null, 'in_window', public.nusuk_club_in_window(cfg));
  end if;
  select * into m from public.nusuk_club_members where user_id = uid;
  if not found then
    return jsonb_build_object('cfg', cfg, 'signed_in', true, 'member', null, 'in_window', public.nusuk_club_in_window(cfg),
      'email', (select email from auth.users where id = uid));
  end if;
  select name into ref_name from public.nusuk_club_members where user_id = m.referred_by;
  return jsonb_build_object(
    'cfg', cfg,
    'signed_in', true,
    'in_window', public.nusuk_club_in_window(cfg),
    'today', today,
    'member', jsonb_build_object(
      'sl', m.sl, 'name', m.name, 'phone', m.phone, 'email', m.email, 'nusuk_code', m.nusuk_code,
      'district', m.district, 'umrah_done', m.umrah_done, 'consent', m.consent,
      'referred_by', ref_name, 'joined', m.created_at),
    'tickets', jsonb_build_object(
      'total', (select count(*) from public.nusuk_club_tickets where user_id = uid),
      'today', (select count(*) from public.nusuk_club_tickets where user_id = uid and day = today),
      'referrals', (select count(*) from public.nusuk_club_tickets where user_id = uid and kind = 'referral'),
      'referrals_today', (select count(*) from public.nusuk_club_tickets where user_id = uid and kind = 'referral' and day = today),
      'copied_today', exists (select 1 from public.nusuk_club_tickets where user_id = uid and kind = 'copy' and day = today)),
    'history', coalesce((
      select jsonb_agg(jsonb_build_object('kind', h.kind, 'day', h.day, 'at', h.created_at, 'from', h.from_name) order by h.created_at desc)
      from (
        select t.kind, t.day, t.created_at, f.name as from_name
        from public.nusuk_club_tickets t
        left join public.nusuk_club_members f on f.user_id = t.from_user
        where t.user_id = uid
        order by t.created_at desc
        limit 40
      ) h), '[]'::jsonb)
  );
end $$;

/** Who owns a referral code (first name + SL only), for the "invited by" line. */
create or replace function public.nusuk_club_ref(p_code text)
returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(
    (select jsonb_build_object('ok', true, 'name', split_part(name, ' ', 1), 'sl', sl)
       from public.nusuk_club_members where lower(nusuk_code) = lower(trim(p_code))),
    jsonb_build_object('ok', false))
$$;

/**
 * Create or update the signed-in member's profile.
 * The first save creates the account and gives the join ticket (+ referral tickets).
 * Nusuk code and referrer are fixed after the first save (shared cards keep working).
 */
create or replace function public.nusuk_club_save(
  p_name text, p_phone text, p_code text, p_district text, p_umrah text, p_consent boolean,
  p_ref text default null, p_device text default null)
returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare
  cfg jsonb := public.nusuk_club_cfg();
  uid uuid := auth.uid();
  v_name text := btrim(regexp_replace(coalesce(p_name, ''), '\s+', ' ', 'g'));
  v_phone text := public.nusuk_club_phone(p_phone);
  v_code text := regexp_replace(coalesce(p_code, ''), '\s', '', 'g');
  v_district text := nullif(btrim(left(coalesce(p_district, ''), 40)), '');
  v_umrah text := case when p_umrah in ('yes', 'no', 'planning') then p_umrah else null end;
  v_device text := case when p_device ~ '^[0-9a-fA-F-]{36}$' then p_device else null end;
  ref public.nusuk_club_members;
  v_ok boolean := false;
  is_new boolean;
begin
  if uid is null then return jsonb_build_object('ok', false, 'reason', 'signin'); end if;
  if char_length(v_name) < 2 or char_length(v_name) > 60 then return jsonb_build_object('ok', false, 'reason', 'name'); end if;
  if v_phone is null then return jsonb_build_object('ok', false, 'reason', 'phone'); end if;
  if exists (select 1 from public.nusuk_club_members where phone = v_phone and user_id <> uid) then
    return jsonb_build_object('ok', false, 'reason', 'phone_taken');
  end if;

  is_new := not exists (select 1 from public.nusuk_club_members where user_id = uid);

  if not is_new then
    update public.nusuk_club_members
       set name = v_name, phone = v_phone, district = v_district, umrah_done = v_umrah,
           consent = coalesce(p_consent, false), updated_at = now()
     where user_id = uid;
    return jsonb_build_object('ok', true, 'created', false);
  end if;

  if not coalesce((cfg->>'on')::boolean, false) then return jsonb_build_object('ok', false, 'reason', 'closed'); end if;
  if v_code !~ '^NG-[A-Za-z0-9]{8}$' then return jsonb_build_object('ok', false, 'reason', 'code'); end if;
  if exists (select 1 from public.nusuk_club_members where lower(nusuk_code) = lower(v_code)) then
    return jsonb_build_object('ok', false, 'reason', 'code_taken');
  end if;

  if nullif(btrim(coalesce(p_ref, '')), '') is not null then
    select * into ref from public.nusuk_club_members where lower(nusuk_code) = lower(btrim(p_ref));
    if not found then return jsonb_build_object('ok', false, 'reason', 'bad_ref'); end if;
    if lower(btrim(p_ref)) = lower(v_code) then return jsonb_build_object('ok', false, 'reason', 'self_ref'); end if;
    -- referral tickets only when this browser is not already a member's device
    -- (stops one person making accounts for themself from one phone)
    v_ok := v_device is not null
      and not exists (select 1 from public.nusuk_club_members where device = v_device);
  end if;

  insert into public.nusuk_club_members (user_id, name, phone, email, nusuk_code, district, umrah_done, consent, referred_by, ref_ok, device)
  values (uid, v_name, v_phone, (select email from auth.users where id = uid), v_code, v_district, v_umrah,
          coalesce(p_consent, false), ref.user_id, v_ok, v_device);

  insert into public.nusuk_club_tickets (user_id, kind) values (uid, 'join') on conflict do nothing;
  if v_ok then
    insert into public.nusuk_club_tickets (user_id, kind, from_user) values (uid, 'ref_bonus', ref.user_id) on conflict do nothing;
    insert into public.nusuk_club_tickets (user_id, kind, from_user) values (ref.user_id, 'referral', uid) on conflict do nothing;
  end if;
  return jsonb_build_object('ok', true, 'created', true, 'ref_counted', v_ok);
exception when unique_violation then
  return jsonb_build_object('ok', false, 'reason', 'busy');
end $$;

/** Called by /nusuk after a signed-in member copies a code: one ticket a day, inside the window. */
create or replace function public.nusuk_club_copy()
returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare
  cfg jsonb := public.nusuk_club_cfg();
  uid uuid := auth.uid();
  n int;
begin
  if uid is null or not exists (select 1 from public.nusuk_club_members where user_id = uid) then
    return jsonb_build_object('ok', false, 'reason', 'member');
  end if;
  if not coalesce((cfg->>'on')::boolean, false) then return jsonb_build_object('ok', false, 'reason', 'closed'); end if;
  if not public.nusuk_club_in_window(cfg) then return jsonb_build_object('ok', false, 'reason', 'window'); end if;
  insert into public.nusuk_club_tickets (user_id, kind) values (uid, 'copy') on conflict do nothing;
  get diagnostics n = row_count;
  return jsonb_build_object('ok', true, 'counted', n > 0);
end $$;

-- ---------- Nusuk Manager ----------
create or replace function public.nusuk_admin_club(p_search text default '', p_limit int default 50, p_offset int default 0)
returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  today date := public.nusuk_today();
  q text := lower(btrim(coalesce(p_search, '')));
begin
  if not public.is_admin() then raise exception 'not allowed'; end if;
  return jsonb_build_object(
    'today', today,
    'stats', jsonb_build_object(
      'members', (select count(*) from public.nusuk_club_members),
      'members_today', (select count(*) from public.nusuk_club_members where (created_at at time zone 'Asia/Dhaka')::date = today),
      'referred', (select count(*) from public.nusuk_club_members where ref_ok),
      'tickets', (select count(*) from public.nusuk_club_tickets),
      'tickets_today', (select count(*) from public.nusuk_club_tickets where day = today),
      'copy_today', (select count(*) from public.nusuk_club_tickets where day = today and kind = 'copy'),
      'holders_today', (select count(distinct user_id) from public.nusuk_club_tickets where day = today)),
    'top', coalesce((
      select jsonb_agg(x order by x.refs desc, x.sl)
      from (
        select m.sl, m.name, m.nusuk_code, count(t.id) as refs
        from public.nusuk_club_members m
        join public.nusuk_club_tickets t on t.user_id = m.user_id and t.kind = 'referral'
        group by m.user_id
        order by refs desc, m.sl
        limit 10
      ) x), '[]'::jsonb),
    'total', (select count(*) from public.nusuk_club_members m
              where q = '' or lower(m.name) like '%' || q || '%' or m.phone like '%' || q || '%'
                 or lower(m.nusuk_code) like '%' || q || '%' or lower(coalesce(m.email, '')) like '%' || q || '%' or m.sl::text = q),
    'rows', coalesce((
      select jsonb_agg(r order by r.sl desc)
      from (
        select m.sl, m.name, m.phone, m.email, m.nusuk_code, m.district, m.umrah_done, m.consent, m.ref_ok,
               m.created_at, rm.name as ref_name, rm.sl as ref_sl,
               (select count(*) from public.nusuk_club_tickets t where t.user_id = m.user_id) as tickets,
               (select count(*) from public.nusuk_club_tickets t where t.user_id = m.user_id and t.day = today) as tickets_today,
               (select count(*) from public.nusuk_club_tickets t where t.user_id = m.user_id and t.kind = 'referral') as referrals
        from public.nusuk_club_members m
        left join public.nusuk_club_members rm on rm.user_id = m.referred_by
        where q = '' or lower(m.name) like '%' || q || '%' or m.phone like '%' || q || '%'
           or lower(m.nusuk_code) like '%' || q || '%' or lower(coalesce(m.email, '')) like '%' || q || '%' or m.sl::text = q
        order by m.sl desc
        limit greatest(1, least(p_limit, 5000)) offset greatest(0, p_offset)
      ) r), '[]'::jsonb)
  );
end $$;

/** Tickets of one day, one row per ticket (for the draw / export). */
create or replace function public.nusuk_admin_club_day(p_day date default null)
returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare d date := coalesce(p_day, public.nusuk_today());
begin
  if not public.is_admin() then raise exception 'not allowed'; end if;
  return jsonb_build_object('day', d, 'rows', coalesce((
    select jsonb_agg(jsonb_build_object('sl', m.sl, 'name', m.name, 'phone', m.phone, 'code', m.nusuk_code, 'tickets', x.n) order by x.n desc, m.sl)
    from (select user_id, count(*) as n from public.nusuk_club_tickets where day = d group by user_id) x
    join public.nusuk_club_members m on m.user_id = x.user_id), '[]'::jsonb));
end $$;

revoke all on function public.nusuk_club_in_window(jsonb) from public;
grant execute on function public.nusuk_club_me() to anon, authenticated;
grant execute on function public.nusuk_club_ref(text) to anon, authenticated;
grant execute on function public.nusuk_club_save(text, text, text, text, text, boolean, text, text) to authenticated;
grant execute on function public.nusuk_club_copy() to authenticated;
grant execute on function public.nusuk_admin_club(text, int, int) to authenticated;
grant execute on function public.nusuk_admin_club_day(date) to authenticated;
